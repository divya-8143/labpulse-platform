export const getBiomarkerByCode = (code: string): BiomarkerCatalogItem | undefined => {
  return BIOMARKER_CATALOG.find((b) => b.code.toLowerCase() === code.toLowerCase());
};

export const searchCatalog = (query: string): BiomarkerCatalogItem[] => {
  const q = query.toLowerCase().trim();
  if (!q) return BIOMARKER_CATALOG;
  return BIOMARKER_CATALOG.filter(
    (b) => b.name.toLowerCase().includes(q) || b.code.toLowerCase().includes(q) || b.category.toLowerCase().includes(q)
  );
};
